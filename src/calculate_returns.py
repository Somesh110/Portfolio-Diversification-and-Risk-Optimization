
# Lesson 2: Calculate investment returns

# Initial investment price
initial_price = 100

# Final investment price
final_price = 85

# Calculate profit
profit = final_price - initial_price

# Calculate percentage return
investment_return = (profit / initial_price) * 100

# Display results
print("Initial Price: Rs.", initial_price)
print("Final Price: Rs.", final_price)
print("Profit: Rs.", profit)
print("Investment Return:", investment_return, "%")
